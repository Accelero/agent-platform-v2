import { createHash } from "node:crypto";
import { format } from "prettier";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

// The schemas are the manager's to enforce; the dashboard only reads their
// descriptions to suggest settings while an administrator types.
const registry = [];
const schemaMetadata = {};
const check = process.argv.includes("--check");
const dir = "src/schemas/generated";
mkdirSync(dir, { recursive: true });
const schemaDirectory = "../../../contracts/hermes-manager/schemas";
for (const [name, file] of [
  ["template", "template-v2.json"],
  ["backend", "terminal-backend-v1.json"],
  ["managed", "hermes-managed-v1.json"],
]) {
  const schema = JSON.parse(readFileSync(`${schemaDirectory}/${file}`, "utf8"));
  registry.push({
    id: schema.$id,
    revision: schema["x-revision"],
    digest: createHash("sha256")
      .update(readFileSync(`${schemaDirectory}/${file}`))
      .digest("hex"),
    compatibleImageDigests: schema["x-compatibleImageDigests"] ?? [],
  });
  schemaMetadata[name] = schema;
}

const path = `${dir}/metadata.ts`;
const content = await format(
  `// Generated by scripts/compile-schemas.mjs; do not edit.\nexport const registry=${JSON.stringify(registry)} as const;\nexport const schemas=${JSON.stringify(schemaMetadata)} as const;\n`,
  { parser: "typescript" },
);
if (check) {
  if (readFileSync(path, "utf8") !== content)
    throw new Error(`Stale schema registry: ${path}`);
} else writeFileSync(path, content);
